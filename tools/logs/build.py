#!/usr/bin/env python3
"""Build the Log Analysis section from report modules.

    python tools/logs/build.py           # rewrite js/data-logs.js (stdlib only)
    python tools/logs/build.py --pdf     # ...and every PDF in assets/logs/
                                         #    (needs reportlab + matplotlib)

Each module in tools/logs/reports/ is one report. It names the facts file it
reads (tools/logs/facts/, written by an analyser such as ulatek.py) and returns
the report as blocks. The same blocks become the web page (js/logs.js renders
them) and the PDF (pdf.py renders them), so the two cannot disagree.

A module is plain Python so its prose can quote computed numbers; it must not
read a combat log. If a number is not in the facts, add it to the analyser.
"""
import importlib.util, io, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)

HEAD = '''/* js/data-logs.js — Log Analysis: pull reviews built from real combat logs.

   GENERATED by tools/logs/build.py from tools/logs/reports/*.py and the facts
   in tools/logs/facts/. Do not edit by hand: change the report module and
   rebuild, or the next build silently undoes the edit.

   One entry per analysed log, newest first. Each is a report written as
   BLOCKS rather than HTML, so the renderer owns the markup:
     lede / p / cap / h3   prose; **bold** and *italic* are the only markup
     ul                    bullet list (ordered:true for a numbered one)
     tiles                 stat tiles: [big, label, tone]  tone = acc | gold | ""
     callout               boxed advice: t, or items for a numbered list
     table                 head, rows; mono = numeric columns; hl = rows to flag
     chart                 kind hp | share | heat | snaps, with its own data

   Strict JSON inside the brackets: check.py parses it, which is the
   missing-comma tripwire the other strict blocks already get. */
const LOGS='''


def load_reports():
    out = []
    rdir = os.path.join(HERE, 'reports')
    for fn in sorted(os.listdir(rdir)):
        if not fn.endswith('.py') or fn.startswith('_'):
            continue
        spec = importlib.util.spec_from_file_location('report_' + fn[:-3].replace('-', '_'), os.path.join(rdir, fn))
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        out.append(mod)
    return out


def facts(name):
    with io.open(os.path.join(HERE, 'facts', name), encoding='utf-8') as f:
        return json.load(f)


J = lambda v: json.dumps(v, ensure_ascii=False, separators=(',', ':'))


def dump(L):
    """One field per line, one block per line: diffable, and still strict JSON."""
    out = [' {']
    for k, v in L.items():
        if k != 'sections':
            out.append('  %s:%s,' % (J(k), J(v)))
    out.append('  "sections":[')
    secs = []
    for s in L['sections']:
        meta = ','.join('%s:%s' % (J(k), J(v)) for k, v in s.items() if k != 'blocks')
        secs.append('   {%s,"blocks":[\n%s]}' % (meta, ',\n'.join('    ' + J(b) for b in s['blocks'])))
    out.append(',\n'.join(secs))
    out.append('  ]}')
    return '\n'.join(out)


def render():
    """(reports, the exact text of js/data-logs.js). Pure: check.py calls it
    to prove the committed file is what the modules produce."""
    logs = []
    for mod in load_reports():
        L = mod.report(facts(mod.FACTS), facts)
        assert L['id'] == mod.ID, (L['id'], mod.ID)
        logs.append(L)
    logs.sort(key=lambda L: L['date'], reverse=True)
    body = '[\n' + ',\n'.join(dump(L) for L in logs) + '\n]'
    json.loads(body)
    return logs, HEAD + body + ';\nconst LOGI=Object.fromEntries(LOGS.map(l=>[l.id,l]));\n'


def main():
    pdf = '--pdf' in sys.argv
    logs, text = render()
    path = os.path.join(ROOT, 'js', 'data-logs.js')
    with io.open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote js/data-logs.js: %d report%s, %.0f KB' % (len(logs), '' if len(logs) == 1 else 's', os.path.getsize(path) / 1024))
    if pdf:
        import pdf as P
        for L in logs:
            if L.get('pdf'):
                P.build(L, os.path.join(ROOT, *L['pdf'].split('/')))
                print('wrote', L['pdf'])


if __name__ == '__main__':
    main()
